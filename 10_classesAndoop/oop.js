// working of new keyword
// step 1 -whenever a new keyword is used , an empty object is created which is known as instance 
// step 2 - a constructor function is called with this keyword pointing to the newly created object
// step 3 - using this keyword all arguments are injected inside the newly created object
// step 4 - at last the newly created object is returned from the constructor function automatically